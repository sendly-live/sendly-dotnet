    [Fact]
    public async Task SendAsync_WithNonAsciiCallerKey_ThrowsValidationExceptionWithoutRequest()
    {
        // Act & Assert
        var exception = await Assert.ThrowsAsync<ValidationException>(
            () => _client.Messages.SendAsync(
                new SendMessageRequest("+15551234567", "Hello!"),
                new IdempotentRequestOptions { IdempotencyKey = "Заказ-42" }));

        Assert.Contains("Idempotency key must be 1-255 printable ASCII characters", exception.Message);
        Assert.Empty(_mockHandler.Requests);
    }

    [Fact]
    public async Task SendAsync_WithTooLongCallerKey_ThrowsValidationExceptionWithoutRequest()
    {
        // Act & Assert
